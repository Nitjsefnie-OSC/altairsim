BDOS	EQU	5
PSTRING	EQU	9
DREG	EQU	58H
CREG	EQU	59H
CR	EQU	0DH
LF	EQU	0AH
	ORG	100H
	LXI	SP,STACK
START:	LXI	D,GREET11
	MVI	C,PSTRING
	CALL	BDOS
	LXI	H,TBL1
	MVI	C,4
TEST1:	MOV	A,M
	OUT	DREG
	INX	H
	DCR	C
	JNZ	TEST1
	MVI	A,6CH
	OUT	CREG
	MVI	C,2
	LXI	H,TBL2
COMP1:	IN	DREG
	CMP	M
	JNZ	ERROR
	INX	H
	DCR	C
	JNZ	COMP1
	IN	CREG
	LXI	D,OKMSG
	MVI	C,PSTRING
	CALL	BDOS
	JMP	0
ERROR:	LXI	D,ERRMSG
	MVI	C,PSTRING
	CALL	BDOS
	JMP	0
GREET11: DB	CR,LF,'9511 TEST BEGUN',CR,LF,'$'
ERRMSG:	DB	CR,LF,'ERROR','$'
OKMSG:	DB	CR,LF,'OK','$'
TBL1:	DB	00,30H,00,40H
TBL2:	DB	70H,00
	DS	32
STACK:	EQU	$
	END
